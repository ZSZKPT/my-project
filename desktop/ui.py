"""Desktop layout, separate from image/upload/template business logic."""
import tkinter as tk
from tkinter import ttk


def build(app):
    root=app.window
    bg='#f1f5f6';ink='#16343b';muted='#647a80';teal='#087f8c'
    root.configure(background=bg)
    root.geometry(f'{min(1320,root.winfo_screenwidth()-60)}x{min(920,root.winfo_screenheight()-70)}')
    root.minsize(1000,680)
    style=ttk.Style(root);style.theme_use('clam')
    style.configure('.',font=('Microsoft YaHei UI',10),background=bg,foreground=ink)
    style.configure('Card.TFrame',background='white')
    style.configure('Card.TLabel',background='white',foreground=ink)
    style.configure('Muted.TLabel',background='white',foreground=muted,font=('Microsoft YaHei UI',9))
    style.configure('Section.TLabel',background='white',font=('Microsoft YaHei UI',11,'bold'))
    style.configure('TEntry',fieldbackground='white',padding=7,bordercolor='#d7e2e4')
    style.configure('TCombobox',padding=6,fieldbackground='white')
    style.configure('TButton',padding=(10,7),background='#e7eff1',borderwidth=0)
    style.map('TButton',background=[('active','#d6e7ea')])
    style.configure('Accent.TButton',background=teal,foreground='white',font=('Microsoft YaHei UI',11,'bold'),padding=(16,12))
    style.map('Accent.TButton',background=[('disabled','#b0c8cb'),('active','#086d78')])
    style.configure('Horizontal.TProgressbar',background=teal,troughcolor='#e3edef',borderwidth=0)
    header=tk.Frame(root,bg='#12343c',padx=24,pady=17);header.pack(fill='x')
    tk.Label(header,text='妙手 · 批量上架助手',bg='#12343c',fg='white',font=('Microsoft YaHei UI',20,'bold')).pack(anchor='w')
    tk.Label(header,text='图片与模板，一次整理。上传图片 → 自动填表 → 妙手手动批量发布',bg='#12343c',fg='#b9d4d9',font=('Microsoft YaHei UI',10)).pack(anchor='w',pady=(5,0))
    app.status_text=tk.StringVar(value='等待准备')
    app.status_label=tk.Label(header,textvariable=app.status_text,bg='#244b53',fg='#d9eff0',padx=13,pady=6,font=('Microsoft YaHei UI',10))
    app.status_label.place(relx=1,x=-2,y=3,anchor='ne')
    body=ttk.Frame(root,padding=16);body.pack(fill='both',expand=True)
    body.columnconfigure(0,minsize=400,weight=0);body.columnconfigure(1,weight=1);body.rowconfigure(0,weight=1)
    left_container=ttk.Frame(body);left_container.grid(row=0,column=0,sticky='nsew',padx=(0,16))
    left_canvas=tk.Canvas(left_container,bg=bg,highlightthickness=0,width=400)
    left_canvas.pack(side='left',fill='both',expand=True)
    left_scroll=ttk.Scrollbar(left_container,orient='vertical',command=left_canvas.yview);left_scroll.pack(side='right',fill='y');left_canvas.configure(yscrollcommand=left_scroll.set)
    left=ttk.Frame(left_canvas);left_id=left_canvas.create_window((0,0),window=left,anchor='nw')
    left.bind('<Configure>',lambda e:left_canvas.configure(scrollregion=left_canvas.bbox('all')))
    left_canvas.bind('<Configure>',lambda e:left_canvas.itemconfigure(left_id,width=e.width))
    def card(parent,title):
        shell=ttk.Frame(parent,style='Card.TFrame',padding=16);shell.pack(fill='x',pady=(0,12))
        ttk.Label(shell,text=title,style='Section.TLabel').pack(anchor='w',pady=(0,10));return shell
    def entry(parent,key,label):
        ttk.Label(parent,text=label,style='Card.TLabel').pack(anchor='w',pady=(7,4));ttk.Entry(parent,textvariable=app.variables[key]).pack(fill='x')
    def path_row(parent,key,label,folder):
        ttk.Label(parent,text=label,style='Card.TLabel').pack(anchor='w',pady=(7,4))
        row=ttk.Frame(parent,style='Card.TFrame');row.pack(fill='x')
        ttk.Entry(row,textvariable=app.variables[key]).pack(side='left',fill='x',expand=True)
        ttk.Button(row,text='选择',command=lambda:app.choose(key,folder)).pack(side='left',padx=(6,0))
    template=card(left,'01  产品模板')
    app.profile_select=ttk.Combobox(template,textvariable=app.selected_profile,values=list(app.profile_paths),state='readonly');app.profile_select.pack(fill='x');app.profile_select.bind('<<ComboboxSelected>>',app.select_template)
    row=ttk.Frame(template,style='Card.TFrame');row.pack(fill='x',pady=(8,0))
    ttk.Button(row,text='编辑 / 另存模板',command=app.edit_template).pack(side='left');ttk.Button(row,text='导入模板',command=app.import_template).pack(side='left',padx=6)
    ttk.Label(template,text='模板保存类目、尺码、重量、标题和固定包装信息。',style='Muted.TLabel',wraplength=340).pack(anchor='w',pady=(9,0))
    files=card(left,'02  文件与标题')
    path_row(files,'source','本地货号图片目录',True);path_row(files,'output','输出目录',True)
    entry(files,'title','中文标题规则（{print_name} 为印花名）')
    entry(files,'price','统一申报价 / CNY')
    ttk.Label(files,text='建议售价自动为申报价的 5 倍。',style='Muted.TLabel').pack(anchor='w',pady=(6,0))
    upload=card(left,'03  图片与上传')
    ttk.Label(upload,text='素材图尺寸',style='Card.TLabel').pack(anchor='w')
    ttk.Combobox(upload,textvariable=app.variables['size'],values=['800','1000','1200'],state='readonly').pack(fill='x',pady=5)
    ttk.Label(upload,text='默认 1000×1000，居中裁切后请核对构图。',style='Muted.TLabel').pack(anchor='w')
    ttk.Label(upload,text='图片链接获取方式',style='Card.TLabel').pack(anchor='w',pady=(10,4))
    ttk.Combobox(upload,textvariable=app.variables['mode'],values=['ImgBB 自动上传','先处理图片，手动补链接'],state='readonly').pack(fill='x')
    ttk.Label(upload,text='ImgBB API Key（仅本次使用）',style='Card.TLabel').pack(anchor='w',pady=(10,4))
    ttk.Entry(upload,textvariable=app.variables['key'],show='*').pack(fill='x')
    ttk.Label(upload,text='上传后图片将公开可访问，密钥不写入模板或日志。',style='Muted.TLabel',wraplength=340).pack(anchor='w',pady=(6,0))
    advanced=card(left,'可选设置')
    path_row(advanced,'links','已有图片链接 CSV',False)
    path_row(advanced,'template','妙手官方服饰导入模板',False)
    ttk.Button(advanced,text='打开 SKU CSV 转换工具',command=app.csv_tool).pack(fill='x',pady=(12,0))
    right=ttk.Frame(body);right.grid(row=0,column=1,sticky='nsew');right.columnconfigure(0,weight=1);right.rowconfigure(0,weight=1)
    names=ttk.Frame(right,style='Card.TFrame',padding=18);names.grid(row=0,column=0,sticky='nsew',pady=(0,12));names.columnconfigure(0,weight=1);names.rowconfigure(2,weight=1)
    top=ttk.Frame(names,style='Card.TFrame');top.grid(row=0,column=0,columnspan=2,sticky='ew')
    ttk.Label(top,text='货号与印花名称',style='Section.TLabel').pack(side='left')
    app.counts_text=tk.StringVar(value='尚未扫描图片')
    ttk.Label(top,textvariable=app.counts_text,style='Muted.TLabel').pack(side='right')
    buttons=ttk.Frame(names,style='Card.TFrame');buttons.grid(row=1,column=0,columnspan=2,sticky='ew',pady=12)
    app.scan_button=ttk.Button(buttons,text='扫描图片目录',command=app.scan);app.scan_button.pack(side='left')
    ttk.Button(buttons,text='导入印花 Excel / CSV',command=app.import_names).pack(side='left',padx=8)
    app.canvas=tk.Canvas(names,bg='white',highlightthickness=1,highlightbackground='#e4edef',height=190);app.canvas.grid(row=2,column=0,sticky='nsew')
    app.table=ttk.Frame(app.canvas,style='Card.TFrame');app.canvas.create_window((0,0),window=app.table,anchor='nw')
    ttk.Label(app.table,text='选择左侧图片目录，然后点击“扫描图片目录”。\n也可以通过 Excel / CSV 批量填写印花名称。',style='Muted.TLabel',padding=20).pack(anchor='w')
    scroll=ttk.Scrollbar(names,orient='vertical',command=app.canvas.yview);scroll.grid(row=2,column=1,sticky='ns');app.canvas.configure(yscrollcommand=scroll.set)
    app.table.bind('<Configure>',lambda e:app.canvas.configure(scrollregion=app.canvas.bbox('all')))
    ttk.Label(names,text='按货号精确匹配印花名；含“前”的图片优先，第一张作为主图。',style='Muted.TLabel').grid(row=3,column=0,columnspan=2,sticky='w',pady=(10,0))
    task=ttk.Frame(right,style='Card.TFrame',padding=18);task.grid(row=1,column=0,sticky='ew')
    top=ttk.Frame(task,style='Card.TFrame');top.pack(fill='x')
    ttk.Label(top,text='任务进度',style='Section.TLabel').pack(side='left')
    app.open_button=ttk.Button(top,text='打开输出目录',command=app.open_output,state='disabled');app.open_button.pack(side='right')
    app.progress_value=tk.DoubleVar(value=0)
    app.progress_bar=ttk.Progressbar(task,maximum=100,variable=app.progress_value);app.progress_bar.pack(fill='x',pady=12)
    app.log=tk.Text(task,height=7,bg='#112d35',fg='#d7eaed',insertbackground='white',font=('Consolas',10),relief='flat',padx=12,pady=10,state='disabled',wrap='word');app.log.pack(fill='x')
    app.run_button=ttk.Button(task,text='开始自动处理并生成妙手表格',style='Accent.TButton',command=app.start);app.run_button.pack(fill='x',pady=(14,8))
    ttk.Label(task,text='生成后请到妙手批量手动导入，选择尺码表及属性，再确认发布。',style='Muted.TLabel',wraplength=600).pack(anchor='w')
